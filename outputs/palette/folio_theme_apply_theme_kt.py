"""
Patches Theme.kt onto the rebuilt, pack-keyed art-direction table.

Five things change:
  1. `chartSeriesDefault` — eight series hues spread round the circle.
  2. `FolioColors`' constructor defaults — the last literal palette hexes in the
     file. They are vestigial (every AppPalette overrides all of them) but the
     brief was to remove *every* old theme hex, so they are regenerated from the
     Gallery light face by replicating `mixA`/`onFillA` here.
  3. The twenty palette `val`s — now `folioArtDirection(<packId>, light = ...)`.
  4. `AppPalette` labels — the face names, so the picker and the palette agree.
  5. `ThemePack.ALL` — Midnight and Honey get their own reader page instead of
     borrowing Gallery's "dark" and Manuscript's "sepia".

Run after folio_theme_apply_rebuild.py:
    python outputs/palette/folio_theme_apply_theme_kt.py
"""

