def patch() -> None:
    src = open(THEME_KT, encoding="utf-8").read()
    lines = src.split("\n")

    # ── 1 + 2: the chart hues and the FolioColors defaults ──
    chart_start = next(i for i, l in enumerate(lines) if "the multi-series/chart hue role" in l)
    while not lines[chart_start].lstrip().startswith("//"):
        chart_start -= 1
    # walk back over the whole leading comment block
    while chart_start > 0 and lines[chart_start - 1].lstrip().startswith("//"):
        chart_start -= 1
    stat = next(i for i, l in enumerate(lines) if re.match(r"\s*val statusBar: Color = ", l))

    head = lines[:chart_start]
    tail = lines[stat + 1:]
    middle = (
        chart_series().split("\n")
        + ["", "data class FolioColors("]
        + folio_colors_defaults().split("\n")
    )
    lines = head + middle + tail

    # ── 3: the palette vals ──
    src = "\n".join(lines)
    vstart = src.index("// The two System faces.")
    vend = src.index("enum class AppPalette(")
    src = src[:vstart] + PALETTE_VALS + "\n\n" + src[vend:]

    # ── 4: AppPalette labels ──
    estart = src.index('    LIGHT("light", ')
    eend = src.index("GarnetFolioColors);") + len("GarnetFolioColors);")
    src = src[:estart] + APP_PALETTE_ENTRIES + src[eend:]

    # ── 5: ThemePack.ALL ──
    pstart = src.index("        val ALL = listOf(")
    pend = src.index("        )", pstart) + len("        )")
    src = src[:pstart] + THEME_PACKS + src[pend:]

    open(THEME_KT, "w", encoding="utf-8").write(src)
    print("Theme.kt: chart hues, FolioColors defaults, palette vals, labels, packs")


if __name__ == "__main__":
    patch()
