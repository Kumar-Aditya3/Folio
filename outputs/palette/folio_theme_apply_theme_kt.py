def mix(a: Color, b: Color, t: float) -> Color:
    """The same straight-line sRGB mix FolioArtDirection.toFolioColors uses."""
    ar = a.convert("srgb")
    br = b.convert("srgb")
    return Color(
        "srgb",
        [
            ar[i] + (br[i] - ar[i]) * t
            for i in range(3)
        ],
    )


def on_fill(c: Color) -> str:
    s = c.convert("srgb")
    luma = 0.299 * s["red"] + 0.587 * s["green"] + 0.114 * s["blue"]
    return "Color(0xFF14110C)" if luma > 0.5 else "Color.White"


def folio_colors_defaults() -> str:
    """Regenerate the vestigial defaults from the Gallery light face."""
    gallery = next(t for t in THEMES if t.pack_id == "gallery")
    r = derive(gallery.light)
    page = r["backgroundBase"]
    ink = r["textPrimary"]
    p, s, t = r["primaryAccent"], r["secondaryAccent"], r["tertiaryAccent"]
    white = Color("white")

    def q(c: Color) -> str:
        return f"Color({argb(c)})"

    rows = [
        ("primary", q(p)),
        ("onPrimary", on_fill(p)),
        ("primaryContainer", q(mix(p, page, 0.72))),
        ("onPrimaryContainer", q(mix(p, ink, 0.62))),
        ("secondary", q(s)),
        ("onSecondary", on_fill(s)),
        ("secondaryContainer", q(mix(s, page, 0.74))),
        ("onSecondaryContainer", q(mix(s, ink, 0.62))),
        ("tertiary", q(t)),
        ("onTertiary", on_fill(t)),
        ("tertiaryContainer", q(mix(t, page, 0.72))),
        ("onTertiaryContainer", q(mix(t, ink, 0.62))),
        ("error", "Color(0xFFC5221F)"),
        ("onError", "Color.White"),
        ("errorContainer", "Color(0xFFF9DEDC)"),
        ("onErrorContainer", "Color(0xFF5F1412)"),
        ("background", q(page)),
        ("onBackground", q(ink)),
        ("surface", q(r["surface"])),
        ("onSurface", q(ink)),
        ("surfaceVariant", q(r["backgroundSecondary"])),
        ("onSurfaceVariant", q(r["textSecondary"])),
        ("surfaceContainerHighest", q(r["surfaceElevated"])),
        ("outline", q(r["border"])),
        ("outlineVariant", q(r["borderHighlight"])),
        ("shadow", "Color.Black"),
        ("scrim", "Color.Black"),
        ("inverseSurface", q(ink)),
        ("inverseOnSurface", q(page)),
        ("inversePrimary", q(mix(p, white, 0.30))),
        ("statusBar", q(ink)),
    ]
    out = []
    for name, value in rows:
        out.append(f"    val {name}: Color = {value},")
    return "\n".join(out)


CHART = """// \u00a712.6: the multi-series/chart hue role. Eight series spread evenly round the
// OKLCH hue circle at one lightness, so a stacked chart reads as eight series and
// not as one colour at eight tints. The first six are the genre breakdown's cap and
// are ordered so no red sits directly beside a green -- the one pairing deuteranopes
// cannot separate -- so adjacent genre rows stay tellable apart without relying on
// hue alone. Reassign or override per palette HERE; feature files never hardcode
// chart hues. Generated by outputs/palette/folio_theme_rebuild.py.
private val chartSeriesDefault: List<Color> = listOf(
    {hexes}
).map {{ Color(it) }}"""


def chart_series() -> str:
    hues = [18, 80, 145, 192, 250, 272, 310, 350]
    cols = [oklch(0.620, 0.135, h) for h in hues]
    hexes = ", ".join(argb(c) for c in cols[:4]) + ",\n    " + ", ".join(
        argb(c) for c in cols[4:]
    )
    return CHART.replace("{hexes}", hexes).replace("{{", "{").replace("}}", "}")


