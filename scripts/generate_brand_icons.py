"""Render the existing Folio vector into Windows and widget assets (Pillow)."""
from pathlib import Path
import re
import xml.etree.ElementTree as ET

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1]
ANDROID = "http://schemas.android.com/apk/res/android"
vector = ET.parse(ROOT / "androidApp/src/main/res/drawable/ic_launcher_foreground.xml")
path = vector.find(".//path").get(f"{{{ANDROID}}}pathData")
contours = []
for contour in path.split("Z"):
    points = [(float(x), float(y)) for x, y in re.findall(r"[ML]([\d.]+),([\d.]+)", contour)]
    if points:
        contours.append(points)

size = 1024
mask = Image.new("1", (size, size))
# Even-odd fill preserves the holes in the leaf.
from PIL import ImageChops
for points in contours:
    layer = Image.new("1", (size, size))
    ImageDraw.Draw(layer).polygon([((x * .76 + 12) * size / 100, (y * .76 + 12) * size / 100)
                                  for x, y in points], fill=1)
    mask = ImageChops.logical_xor(mask, layer)

image = Image.new("RGBA", (size, size))
pixels = image.load()
for y in range(size):
    for x in range(size):
        t = max(0, min(1, (x / size + 1 - y / size) / 2))
        a, b, u = ((39, 55, 142), (19, 123, 144), t / .52) if t < .52 else (
            (19, 123, 144), (34, 156, 129), (t - .52) / .48)
        pixels[x, y] = (*[round(p + (q - p) * u) for p, q in zip(a, b)], 255)
image.putalpha(mask.convert("L"))
image = image.resize((256, 256), Image.Resampling.LANCZOS)
image.save(ROOT / "icon/Folio.png")
image.save(ROOT / "icon/Folio.ico", sizes=[(s, s) for s in (16, 20, 24, 32, 40, 48, 64, 128, 256)])
(ROOT / "androidApp/src/main/res/drawable/ic_folio_mark.xml").write_text(
    '<?xml version="1.0" encoding="utf-8"?>\n'
    '<!-- Generated by scripts/generate_brand_icons.py from the launcher vector. -->\n'
    f'<vector xmlns:android="{ANDROID}" android:width="24dp" android:height="24dp" '
    'android:viewportWidth="100" android:viewportHeight="100">\n'
    f'    <path android:fillColor="#137B90" android:fillType="evenOdd" android:pathData="{path}" />\n'
    '</vector>\n', encoding="utf-8")
