// ── True Light / True Dark ────────────────────────────────────────────────
// The two achromatic system faces, redesigned. The old pair separated its
// planes by lightness alone on a flat grey — "background #FFFFFF over a
// #F2F2F2 card" — which is why the default theme read as a wireframe beside
// the nine art directions. They are now art-directed in their own right:
// a genuinely white canvas with a real ladder and a cobalt signature
// (Daylight), and a true-black canvas with a cool slate-blue depth
// (Midnight). Both keep the property that makes them the defaults — no hue
// in the paper or in the black itself — so the room stays neutral while the
// accents, the guilloche and the atmosphere carry the identity.
//
// Both stay in ThemeSchemeTest's `achromaticByDesign`: their *planes* are
// still hue-free, so they satisfy Rule 22 through the luminance clause
// (surface vs background ΔL* >= 4.0), not the hue clause. The hue lives in
// the accents and in the field the atmosphere places from them.

// -- the ten themes, as art directions ------------------------------------------------------
// Each theme is an *art direction*, not a derivation. See [FolioArtDirection]: it authors
// every role a designer actually chooses -- two page planes, two card planes, four accents,
// three guilloche hues, two glows, progress, a three-tier ink ladder, two edges and a
// navigation accent -- and derives only the *relationships* (containers, `on*` inks, the
// inverse family).
//
// The old `lightScheme`/`darkScheme` derivation is deliberately gone. A role set can be
// derived; a *palette* is an artistic decision, and a decision cannot be derived from
// itself -- which is precisely why every previous room collapsed onto one hue at several
// lightnesses.
//
// The table is keyed by the **theme pack's own id**, which is the same id
// `LocalFolioPackId` carries and the same id the background field, the lamp and the
// guilloche geometry are keyed on. There is no second "family" id space any more.
//
// The AppPalette ids below are unchanged, so a persisted `appThemeId` still lands on its
// own theme; only the colours behind them are new.

